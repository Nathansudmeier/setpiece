export type CmsSlug = keyof typeof CMS_SCHEMA;
export type CmsCopy = Record<string, string>;
export const CMS_SLUGS = Object.keys(CMS_SCHEMA) as CmsSlug[];
export function isCmsSlug(value: string): value is CmsSlug {
  return Object.hasOwn(CMS_SCHEMA, value);
}
export function defaultsFor(slug: CmsSlug): CmsCopy {
  return Object.fromEntries(
    Object.entries(CMS_SCHEMA[slug].fields).map(([key, f]) => [key, f.value]),
  );
}
export function validateCms(slug: CmsSlug, input: unknown): CmsCopy {
  if (!input || typeof input !== "object" || Array.isArray(input))
    throw new Error("Ongeldige inhoud.");
  const fields = CMS_SCHEMA[slug].fields;
  const data = input as Record<string, unknown>;
  if (
    Object.keys(data).length !== Object.keys(fields).length ||
    Object.keys(data).some((k) => !Object.hasOwn(fields, k))
  )
    throw new Error("De velden zijn gewijzigd. Ververs de editor.");
  for (const [k, f] of Object.entries(fields)) {
    const value = data[k];
    if (typeof value !== "string" || !value.trim() || value.length > 10000)
      throw new Error("Vul alle velden in met maximaal 10.000 tekens.");
    if (f.type === "link") {
      if (value.startsWith("/")) {
        if (
          value.startsWith("//") ||
          value.includes("\\") ||
          /[\s\u0000-\u001f]/.test(value)
        )
          throw new Error("Gebruik een veilig lokaal pad.");
      } else {
        let u: URL;
        try {
          u = new URL(value);
        } catch {
          throw new Error("Gebruik een volledige link.");
        }
        if (
          !["https:", "http:", "mailto:", "tel:"].includes(u.protocol) ||
          u.username ||
          u.password
        )
          throw new Error("Gebruik een veilige link.");
      }
    }
  }
  return data as CmsCopy;
}
